//! Video: VP8, what LiveKit's web clients (Element Call, the WebView
//! build) send and expect, through libvpx.
//!
//! - [`Frame`]: a picture as 8-bit I420 (a full-size Y plane, then U and V
//!   at half size), the form both cameras and libvpx deal in.
//! - [`Vp8Decoder`]: a remote track's frames, as str0m hands them over
//!   (whole, depacketized), back into pictures.
//! - [`Vp8Encoder`]: pictures into frames to send, at a set bitrate, with
//!   a keyframe on request (someone joined, or lost packets).

use std::ptr;

#[allow(non_upper_case_globals, non_camel_case_types, non_snake_case, dead_code, clippy::all)]
mod ffi {
    // Generated by bindgen 0.71 from libvpx 1.17's vpx_decoder.h,
    // vpx_encoder.h, vp8dx.h and vp8cx.h.
    include!("video_ffi.rs");
}

#[derive(Debug, thiserror::Error)]
#[error("VP8 {action}: {message}")]
pub struct VideoError {
    action: &'static str,
    message: String,
}

pub type Result<T, E = VideoError> = std::result::Result<T, E>;

fn check(action: &'static str, ctx: &ffi::vpx_codec_ctx_t, code: ffi::vpx_codec_err_t) -> Result<()> {
    if code == ffi::vpx_codec_err_t_VPX_CODEC_OK {
        return Ok(());
    }
    // SAFETY: libvpx returns static C strings for errors; the context's
    // detail, when set, lives as long as the context.
    let message = unsafe {
        let detail = ctx.err_detail;
        let text = if detail.is_null() { ffi::vpx_codec_err_to_string(code) } else { detail };
        std::ffi::CStr::from_ptr(text).to_string_lossy().into_owned()
    };
    Err(VideoError { action, message })
}

/// A picture in 8-bit I420, planes packed tight.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Frame {
    pub width: u32,
    pub height: u32,
    /// Y (`width × height`), then U and V (each `⌈w/2⌉ × ⌈h/2⌉`).
    pub data: Vec<u8>,
}

impl Frame {
    pub fn chroma_size(width: u32, height: u32) -> (u32, u32) {
        (width.div_ceil(2), height.div_ceil(2))
    }

    /// A black picture of this size.
    pub fn black(width: u32, height: u32) -> Frame {
        let (cw, ch) = Frame::chroma_size(width, height);
        let luma = (width * height) as usize;
        let chroma = (cw * ch) as usize;
        let mut data = vec![16u8; luma + 2 * chroma];
        data[luma..].fill(128);
        Frame { width, height, data }
    }

    /// Half the size each way, each pixel the average of four (an odd
    /// edge keeps its last row or column).
    pub fn half(&self) -> Frame {
        let (w, h) = (self.width.div_ceil(2).max(1), self.height.div_ceil(2).max(1));
        let mut out = Frame::black(w, h);
        let shrink = |src: &[u8], sw: u32, sh: u32, dst: &mut [u8], dw: u32, dh: u32| {
            let (sw, sh, dw) = (sw as usize, sh as usize, dw as usize);
            for y in 0..dh as usize {
                let (y0, y1) = ((2 * y).min(sh - 1), (2 * y + 1).min(sh - 1));
                for x in 0..dw {
                    let (x0, x1) = ((2 * x).min(sw - 1), (2 * x + 1).min(sw - 1));
                    let sum = u32::from(src[y0 * sw + x0]) + u32::from(src[y0 * sw + x1]) + u32::from(src[y1 * sw + x0]) + u32::from(src[y1 * sw + x1]);
                    dst[y * dw + x] = ((sum + 2) / 4) as u8;
                }
            }
        };
        let (scw, sch) = Frame::chroma_size(self.width, self.height);
        let (dcw, dch) = Frame::chroma_size(w, h);
        let luma = (w * h) as usize;
        let chroma = (dcw * dch) as usize;
        let (y, rest) = out.data.split_at_mut(luma);
        let (u, v) = rest.split_at_mut(chroma);
        shrink(self.y(), self.width, self.height, y, w, h);
        shrink(self.u(), scw, sch, u, dcw, dch);
        shrink(self.v(), scw, sch, v, dcw, dch);
        out
    }

    pub fn y(&self) -> &[u8] {
        &self.data[..(self.width * self.height) as usize]
    }

    pub fn u(&self) -> &[u8] {
        let luma = (self.width * self.height) as usize;
        let (cw, ch) = Frame::chroma_size(self.width, self.height);
        &self.data[luma..luma + (cw * ch) as usize]
    }

    pub fn v(&self) -> &[u8] {
        let luma = (self.width * self.height) as usize;
        let (cw, ch) = Frame::chroma_size(self.width, self.height);
        &self.data[luma + (cw * ch) as usize..]
    }

    /// Copy a libvpx image out, dropping its stride padding.
    ///
    /// # Safety
    /// `img` must be a valid I420 image libvpx just handed over.
    unsafe fn from_image(img: &ffi::vpx_image_t) -> Frame {
        let (width, height) = (img.d_w, img.d_h);
        let (cw, ch) = Frame::chroma_size(width, height);
        let mut data = Vec::with_capacity((width * height + 2 * cw * ch) as usize);
        for (plane, (w, h)) in [(0, (width, height)), (1, (cw, ch)), (2, (cw, ch))] {
            let stride = img.stride[plane] as usize;
            for row in 0..h as usize {
                // SAFETY: each row is `stride` apart and at least `w` long.
                let start = unsafe { img.planes[plane].add(row * stride) };
                data.extend_from_slice(unsafe { std::slice::from_raw_parts(start, w as usize) });
            }
        }
        Frame { width, height, data }
    }
}

/// One remote track's VP8 decoder.
pub struct Vp8Decoder {
    ctx: Box<ffi::vpx_codec_ctx_t>,
}

// SAFETY: the context is used from one thread at a time (`&mut self`).
unsafe impl Send for Vp8Decoder {}

impl Vp8Decoder {
    pub fn new() -> Result<Vp8Decoder> {
        let mut ctx = Box::<ffi::vpx_codec_ctx_t>::default();
        // SAFETY: a fresh context, libvpx's own VP8 interface, default config.
        let code = unsafe { ffi::vpx_codec_dec_init_ver(&mut *ctx, ffi::vpx_codec_vp8_dx(), ptr::null(), 0, ffi::VPX_DECODER_ABI_VERSION as i32) };
        check("decoder", &ctx, code)?;
        Ok(Vp8Decoder { ctx })
    }

    /// Decode one whole frame; the picture it shows, if any.
    pub fn decode(&mut self, frame: &[u8]) -> Result<Option<Frame>> {
        // SAFETY: the data outlives the call; images returned are valid
        // until the next decode, and copied out before then.
        unsafe {
            let code = ffi::vpx_codec_decode(&mut *self.ctx, frame.as_ptr(), frame.len() as u32, ptr::null_mut(), 0);
            check("decode", &self.ctx, code)?;
            let mut iter: ffi::vpx_codec_iter_t = ptr::null();
            let mut last = None;
            loop {
                let img = ffi::vpx_codec_get_frame(&mut *self.ctx, &mut iter);
                if img.is_null() {
                    break;
                }
                last = Some(Frame::from_image(&*img));
            }
            Ok(last)
        }
    }
}

impl Drop for Vp8Decoder {
    fn drop(&mut self) {
        // SAFETY: initialised in `new`.
        unsafe { ffi::vpx_codec_destroy(&mut *self.ctx) };
    }
}

/// A VP8 encoder for one outgoing track.
pub struct Vp8Encoder {
    ctx: Box<ffi::vpx_codec_ctx_t>,
    width: u32,
    height: u32,
}

// SAFETY: as the decoder.
unsafe impl Send for Vp8Encoder {}

/// An encoded frame, ready for the packetizer.
#[derive(Debug, Clone)]
pub struct Encoded {
    pub data: Vec<u8>,
    pub keyframe: bool,
}

impl Vp8Encoder {
    /// `bitrate` in kbit/s. Real-time settings: no lookahead, constant
    /// bitrate, error-resilient, dropping frames rather than falling behind.
    pub fn new(width: u32, height: u32, bitrate: u32) -> Result<Vp8Encoder> {
        let mut ctx = Box::<ffi::vpx_codec_ctx_t>::default();
        // SAFETY: plain calls with valid pointers to owned structs.
        unsafe {
            let iface = ffi::vpx_codec_vp8_cx();
            let mut cfg = ffi::vpx_codec_enc_cfg_t::default();
            check("defaults", &ctx, ffi::vpx_codec_enc_config_default(iface, &mut cfg, 0))?;
            cfg.g_w = width;
            cfg.g_h = height;
            // Timestamps in milliseconds.
            cfg.g_timebase = ffi::vpx_rational { num: 1, den: 1000 };
            cfg.g_threads = std::thread::available_parallelism().map_or(2, |n| n.get().min(4) as u32);
            cfg.g_lag_in_frames = 0;
            cfg.g_error_resilient = ffi::VPX_ERROR_RESILIENT_DEFAULT;
            cfg.rc_end_usage = ffi::vpx_rc_mode_VPX_CBR;
            cfg.rc_target_bitrate = bitrate;
            cfg.rc_min_quantizer = 4;
            cfg.rc_max_quantizer = 56;
            cfg.rc_dropframe_thresh = 25;
            // A keyframe at least every few seconds, more on request.
            cfg.kf_max_dist = 3000;
            let code = ffi::vpx_codec_enc_init_ver(&mut *ctx, iface, &cfg, 0, ffi::VPX_ENCODER_ABI_VERSION as i32);
            check("encoder", &ctx, code)?;
            // Faster than the default, as real-time video wants.
            let code = ffi::vpx_codec_control_(&mut *ctx, ffi::vp8e_enc_control_id_VP8E_SET_CPUUSED as i32, -6i32);
            check("speed", &ctx, code)?;
        }
        Ok(Vp8Encoder { ctx, width, height })
    }

    pub fn size(&self) -> (u32, u32) {
        (self.width, self.height)
    }

    /// Encode `frame` (this encoder's size), at `at_ms`; `keyframe`
    /// forces a full picture.
    pub fn encode(&mut self, frame: &Frame, at_ms: i64, keyframe: bool) -> Result<Vec<Encoded>> {
        assert_eq!((frame.width, frame.height), (self.width, self.height), "frame size differs from the encoder's");
        let mut out = Vec::new();
        // SAFETY: the image wraps `frame`'s buffer, which outlives the
        // encode call; packets are copied out before the next call.
        unsafe {
            let mut img = ffi::vpx_image_t::default();
            let wrapped = ffi::vpx_img_wrap(&mut img, ffi::vpx_img_fmt_VPX_IMG_FMT_I420, self.width, self.height, 1, frame.data.as_ptr() as *mut u8);
            if wrapped.is_null() {
                return Err(VideoError { action: "encode", message: "couldn't wrap the picture".into() });
            }
            let flags: ffi::vpx_enc_frame_flags_t = if keyframe { ffi::VPX_EFLAG_FORCE_KF as _ } else { 0 };
            let code = ffi::vpx_codec_encode(&mut *self.ctx, &img, at_ms, 33, flags, ffi::VPX_DL_REALTIME as _);
            check("encode", &self.ctx, code)?;
            let mut iter: ffi::vpx_codec_iter_t = ptr::null();
            loop {
                let packet = ffi::vpx_codec_get_cx_data(&mut *self.ctx, &mut iter);
                if packet.is_null() {
                    break;
                }
                if (*packet).kind == ffi::vpx_codec_cx_pkt_kind_VPX_CODEC_CX_FRAME_PKT {
                    let f = (*packet).data.frame;
                    out.push(Encoded {
                        data: std::slice::from_raw_parts(f.buf as *const u8, f.sz).to_vec(),
                        keyframe: f.flags & ffi::VPX_FRAME_IS_KEY != 0,
                    });
                }
            }
        }
        Ok(out)
    }
}

impl Drop for Vp8Encoder {
    fn drop(&mut self) {
        // SAFETY: initialised in `new`.
        unsafe { ffi::vpx_codec_destroy(&mut *self.ctx) };
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A test card: horizontal ramps in Y, flat chroma.
    fn card(width: u32, height: u32, shift: u32) -> Frame {
        let mut frame = Frame::black(width, height);
        for row in 0..height {
            for col in 0..width {
                frame.data[(row * width + col) as usize] = ((col + shift) * 255 / width.max(1)) as u8;
            }
        }
        frame
    }

    #[test]
    fn pictures_survive_vp8() {
        let (w, h) = (320, 180);
        let mut encoder = Vp8Encoder::new(w, h, 800).unwrap();
        let mut decoder = Vp8Decoder::new().unwrap();
        let mut decoded = Vec::new();
        for i in 0..10 {
            for packet in encoder.encode(&card(w, h, i * 4), i64::from(i) * 33, i == 0).unwrap() {
                assert_eq!(packet.keyframe, i == 0, "frame {i}");
                decoded.extend(decoder.decode(&packet.data).unwrap());
            }
        }
        assert!(decoded.len() >= 8, "only {} frames came back", decoded.len());
        let last = decoded.last().unwrap();
        assert_eq!((last.width, last.height), (w, h));
        assert_eq!(last.data.len(), (w * h + 2 * 160 * 90) as usize);
        // Close to the card, as lossy coding goes.
        let original = card(w, h, 9 * 4);
        let error: f64 = last.y().iter().zip(original.y()).map(|(a, b)| (f64::from(*a) - f64::from(*b)).abs()).sum::<f64>() / f64::from(w * h);
        assert!(error < 6., "mean luma error {error}");
    }

    #[test]
    fn halving_averages_and_rounds_sizes_up() {
        let mut frame = Frame::black(4, 2);
        frame.data[..8].copy_from_slice(&[0, 100, 200, 200, 100, 0, 200, 200]);
        let half = frame.half();
        assert_eq!((half.width, half.height), (2, 1));
        assert_eq!(half.y(), &[50, 200]);
        assert_eq!(Frame::black(5, 3).half().width, 3);
        let quarter = Frame::black(1280, 720).half().half();
        assert_eq!((quarter.width, quarter.height), (320, 180));
    }

    #[test]
    fn odd_sizes_have_rounded_up_chroma() {
        let frame = Frame::black(5, 3);
        assert_eq!((frame.y().len(), frame.u().len(), frame.v().len()), (15, 6, 6));
    }
}
